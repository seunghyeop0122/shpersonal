-- =========================================================
-- 지원 회사 진행상태를 전형 단계로 통합
--   예전: status = 진행중 / 결과완료,  stage = 세부 단계(따로)
--   지금: status 하나에 전형 단계(서류 지원 / 서류 탈락 / 서류 합격 /
--         인적성·필기 / 1차 면접 / 2차 면접 / 최종 면접 / 최종 합격 / 최종 탈락)
--
--   세부 단계(stage) 값이 전형 단계와 같으면 그대로 진행상태로 옮기고
--   ('지원 완료' 는 '서류 지원'), 세부 단계가 없던 '진행중' 은 '서류 지원' 으로 바꾼다.
--   예전 값만 건드리므로 다시 실행돼도 안전하다. stage 열은 지우지 않고 그대로 둔다.
-- =========================================================

alter table public.companies alter column status set default '서류 지원';

update public.companies
   set status = case
     when stage = '지원 완료' then '서류 지원'
     when stage in ('서류 탈락', '서류 합격', '인적성·필기', '1차 면접', '2차 면접',
                    '최종 면접', '최종 합격', '최종 탈락') then stage
     when status = '진행중' then '서류 지원'
     else status
   end
 where status in ('진행중', '결과완료');
